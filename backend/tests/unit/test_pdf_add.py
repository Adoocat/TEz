@pytest.fixture
def library(tmp_path: Path) -> Library:
    return open_library(tmp_path / "lib", create=True)


@pytest.fixture
def client(library: Library) -> Iterator[TestClient]:
    app = create_app(
        token=TOKEN, settings=Settings(), library=library, secret_store=MemorySecretStore()
    )
    with TestClient(app, headers=AUTH, raise_server_exceptions=False) as c:
        yield c


def upload(client: TestClient, data: bytes, name: str = "Smith_2024-code-review.pdf", **query: str):
    return client.post(
        "/pdfs",
        params={"file_name": name, **query},
        content=data,
        headers={"Content-Type": "application/pdf"},
    )


def run_jobs(library: Library) -> None:
    worker = Worker(library.db, registry, lease=timedelta(seconds=30))
    while worker.run_once():
        pass


def count(library: Library, model: type[object]) -> int:
    with library.db.session() as session:
        return session.query(model).count()


def test_a_pdf_becomes_a_paper_in_the_inbox_and_is_stored_under_its_hash(
    client: TestClient, library: Library
) -> None:
    data = make_pdf(3)

    response = upload(client, data)

    assert response.status_code == 201, response.text
    added = response.json()
    assert added["status"] == "added"
    assert added["job_id"] is not None
    with library.db.session() as session:
        attachment = session.get(Attachment, added["attachment_id"])
        assert attachment is not None
        paper = session.get(Paper, added["paper_id"])
        assert paper is not None
        assert paper.title == "Smith 2024 code review"
        assert paper.library_added_at is not None
        inbox = session.query(Collection).filter_by(is_system=True, name=INBOX).one()
        assert session.query(CollectionPaper).filter_by(collection_id=inbox.id).count() == 1
        stored = library.path / attachment.rel_path
        assert attachment.rel_path == f"files/{attachment.sha256[:2]}/{attachment.sha256}.pdf"
        assert (attachment.file_name, attachment.size) == ("Smith_2024-code-review.pdf", len(data))
    assert stored.read_bytes() == data


def test_the_same_pdf_is_not_added_twice(client: TestClient, library: Library) -> None:
    data = make_pdf(2)
    first = upload(client, data).json()

    again = upload(client, data, name="renamed copy.pdf")

    assert again.status_code == 201
    assert again.json() == {
        "status": "duplicate",
        "paper_id": first["paper_id"],
        "attachment_id": first["attachment_id"],
        "job_id": None,
        "file_name": "renamed copy.pdf",
    }
    assert count(library, Paper) == 1
    assert count(library, Attachment) == 1
    assert len(list((library.path / "files").rglob("*.pdf"))) == 1


def test_inspection_counts_pages_and_finds_the_text_layer(
    client: TestClient, library: Library
) -> None:
    with_text = upload(client, make_pdf(3, tag="a")).json()
    scanned = upload(client, make_pdf(2, text=None, tag="b"), name="scan.pdf").json()

    run_jobs(library)

    text_view = client.get(f"/attachments/{with_text['attachment_id']}").json()
    assert (text_view["page_count"], text_view["text_status"]) == (3, "ok")
    assert text_view["error"] is None
    scan_view = client.get(f"/attachments/{scanned['attachment_id']}").json()
    assert (scan_view["page_count"], scan_view["text_status"]) == (2, "needs_ocr")


def test_a_broken_pdf_is_marked_and_the_app_keeps_working(
    client: TestClient, library: Library
) -> None:
    added = upload(client, broken_pdf(), name="cut-off.pdf").json()

    run_jobs(library)

    view = client.get(f"/attachments/{added['attachment_id']}").json()
    assert view["text_status"] == "failed"
    assert view["error"]["code"] == "pdf.unreadable"
    assert view["page_count"] is None
    with library.db.session() as session:
        job = session.get(ProcessingJob, added["job_id"])
        assert job is not None and job.status is JobStatus.DONE  # broken is an answer, not a retry
    # And the next file still goes in.
    assert upload(client, make_pdf(1)).json()["status"] == "added"


def test_a_file_that_crashes_the_worker_is_marked_on_its_last_attempt(
    client: TestClient, library: Library, monkeypatch: pytest.MonkeyPatch
) -> None:
    added = upload(client, make_pdf(1)).json()

    class ProcessDied(BaseException):
        """Stands in for PDFium taking the process down: nothing after it runs."""

    def crash(_: Path) -> None:
        raise ProcessDied

    monkeypatch.setattr(files_service, "inspect_pdf", crash)
    ctx = JobContext("job", db=library.db, attempt=3, max_attempts=3)
    with pytest.raises(ProcessDied):
        files_service.inspect_attachment({"attachment_id": added["attachment_id"]}, ctx)

    view = client.get(f"/attachments/{added['attachment_id']}").json()
    assert view["text_status"] == "failed"
    assert view["error"] == {"code": "pdf.crashed", "params": {"attempts": 3}}


def test_a_file_that_is_not_a_pdf_is_refused_and_nothing_is_stored(
    client: TestClient, library: Library
) -> None:
    response = upload(client, b"<html>not a pdf</html>", name="page.pdf")

    assert response.status_code == 422
    assert response.json()["error"] == {
        "code": "pdf.not_a_pdf",
        "params": {"file_name": "page.pdf"},
    }
    assert count(library, Paper) == 0
    assert not list((library.path / "files").rglob("*.pdf"))


def test_a_too_large_file_is_refused(client: TestClient, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(files_service, "MAX_PDF_BYTES", 100)

    response = upload(client, make_pdf(1))

    assert response.status_code == 413
    assert response.json()["error"]["code"] == "pdf.too_large"


def test_a_pdf_can_be_attached_to_an_existing_paper(client: TestClient, library: Library) -> None:
    with library.db.write_session() as session:
        paper_id = PaperService(session).add("Known paper", identifiers={}, authors=[]).id

    added = upload(client, make_pdf(1), paper_id=paper_id).json()

    assert added["paper_id"] == paper_id
    assert count(library, Paper) == 1
    listed = client.get(f"/papers/{paper_id}/attachments").json()
    assert [a["id"] for a in listed] == [added["attachment_id"]]

    missing = upload(client, make_pdf(1, tag="x"), paper_id="nope")
    assert missing.status_code == 404
    assert missing.json()["error"]["code"] == "paper.not_found"


def test_pdfs_from_paths_succeed_or_fail_one_by_one(
    client: TestClient, library: Library, tmp_path: Path
) -> None:
    good = tmp_path / "good.pdf"
    good.write_bytes(make_pdf(1))
    not_pdf = tmp_path / "notes.pdf"
    not_pdf.write_text("hello", encoding="utf-8")
    missing = tmp_path / "missing.pdf"

    response = client.post(
        "/pdfs/from-paths", json={"paths": [str(good), str(not_pdf), str(missing), str(good)]}
    )

    assert response.status_code == 200
    results = response.json()
    assert results[0]["added"]["status"] == "added"
    assert results[0]["added"]["file_name"] == "good.pdf"
    assert results[1]["error"]["code"] == "pdf.not_a_pdf"
    assert results[2]["error"] == {"code": "pdf.file_not_found", "params": {"path": str(missing)}}
    assert results[3]["added"]["status"] == "duplicate"
    assert count(library, Attachment) == 1


def test_an_unknown_attachment_is_404(client: TestClient) -> None:
    response = client.get("/attachments/nope")

    assert response.status_code == 404
    assert response.json()["error"]["code"] == "attachment.not_found"
