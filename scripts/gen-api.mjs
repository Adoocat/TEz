// `pnpm gen:api`: regenerate the frontend's API types from the backend's OpenAPI schema.
// `pnpm gen:api --check` (part of `pnpm check api`, run in CI) only compares and exits 1
// when the committed files are out of date, so the client can never drift from the API.
//
//   backend (FastAPI) --python -m tez.openapi--> apps/web/src/api/openapi.json
//                     --openapi-typescript-----> apps/web/src/api/schema.d.ts
import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

import { root } from "./lib/run.mjs";

const outDir = path.join(root, "apps", "web", "src", "api");
const banner = "// Generated by `pnpm gen:api` from the backend's OpenAPI schema. Do not edit.\n\n";
const check = process.argv.includes("--check");

const dump = spawnSync("uv", ["run", "--project", "backend", "python", "-m", "tez.openapi"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
if (dump.status !== 0) {
  process.stderr.write(dump.stderr);
  console.error("gen:api: could not read the OpenAPI schema from the backend");
  process.exit(1);
}

const schemaJson = dump.stdout;
const types = banner + astToString(await openapiTS(JSON.parse(schemaJson)));
const outputs = [
  [path.join(outDir, "openapi.json"), schemaJson],
  [path.join(outDir, "schema.d.ts"), types],
];

const read = async (file) => readFile(file, "utf8").catch(() => null);
const stale = [];
for (const [file, content] of outputs) {
  if ((await read(file)) !== content) stale.push(file);
}

if (check) {
  if (stale.length > 0) {
    console.error("gen:api: the API client is out of date with the backend:");
    for (const file of stale) console.error(`  ${path.relative(root, file)}`);
    console.error("Run `pnpm gen:api` and commit the result.");
    process.exit(1);
  }
  console.log("gen:api: the API client is up to date");
} else {
  for (const [file, content] of outputs) await writeFile(file, content);
  console.log(
    stale.length > 0 ? `gen:api: updated ${stale.length} file(s)` : "gen:api: no changes",
  );
}
