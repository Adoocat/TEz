// `pnpm gen:tokens`: turn docs/design/tokens.json into CSS variables for the frontend.
// `--check` (part of `pnpm check web`) fails when the committed CSS is out of date.
//
// Names follow docs/design/README.md: `color.bg.canvas` -> `--color-bg-canvas`. Colors come in
// a light set (on :root) and a dark set (on [data-theme="dark"]); `type.<name>` becomes
// `--type-<name>-{font,size,weight,line-height}`.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { root } from "./lib/run.mjs";

const source = path.join(root, "docs", "design", "tokens.json");
const target = path.join(root, "apps", "web", "src", "styles", "tokens.css");
const check = process.argv.includes("--check");

const tokens = JSON.parse(await readFile(source, "utf8"));

const kebab = (key) => key.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

function flatten(value, prefix, out) {
  if (value !== null && typeof value === "object") {
    for (const [key, child] of Object.entries(value))
      flatten(child, `${prefix}-${kebab(key)}`, out);
  } else {
    out.push([prefix, String(value)]);
  }
  return out;
}

const statics = [];
for (const [group, value] of Object.entries(tokens)) {
  if (group.startsWith("$") || group === "color") continue;
  if (group === "type") {
    for (const [name, style] of Object.entries(value)) {
      statics.push(
        [`--type-${name}-font`, `var(--font-${style.font})`],
        [`--type-${name}-size`, style.size],
        [`--type-${name}-weight`, String(style.weight)],
        [`--type-${name}-line-height`, style.lineHeight],
      );
    }
    continue;
  }
  flatten(value, `--${kebab(group)}`, statics);
}

const block = (selector, entries, extra = []) =>
  [
    `${selector} {`,
    ...extra.map((l) => `  ${l}`),
    ...entries.map(([k, v]) => `  ${k}: ${v};`),
    "}",
  ].join("\n");

const css = [
  "/* Generated by `pnpm gen:tokens` from docs/design/tokens.json. Do not edit. */",
  "",
  block(
    ":root",
    [...flatten(tokens.color.light, "--color", []), ...statics],
    ["color-scheme: light;"],
  ),
  "",
  block(':root[data-theme="dark"]', flatten(tokens.color.dark, "--color", []), [
    "color-scheme: dark;",
  ]),
  "",
].join("\n");

const current = await readFile(target, "utf8").catch(() => null);
if (check) {
  if (current !== css) {
    console.error("gen:tokens: apps/web/src/styles/tokens.css is out of date with tokens.json.");
    console.error("Run `pnpm gen:tokens` and commit the result.");
    process.exit(1);
  }
  console.log("gen:tokens: up to date");
} else {
  await writeFile(target, css);
  console.log(current === css ? "gen:tokens: no changes" : "gen:tokens: updated tokens.css");
}
